import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const packageRoot = new URL("../pkg/godot-cymonkey/", import.meta.url);
const registry = await readFile(new URL("addons/jangolova_cymonkey/cymonkey_registry.gd", packageRoot), "utf8");
const protocol = await readFile(new URL("addons/jangolova_cymonkey/cymonkey_protocol.gd", packageRoot), "utf8");
const host = await readFile(new URL("addons/jangolova_cymonkey/cymonkey_websocket_host.gd", packageRoot), "utf8");
const fixture = await readFile(new URL("godot-cymonkey-fixture/fixture.gd", import.meta.url), "utf8");
const scene = await readFile(new URL("godot-cymonkey-fixture/fixture.tscn", import.meta.url), "utf8");
const scenePlan = JSON.parse(await readFile(new URL("godot-cymonkey-fixture/house.scene-plan.json", import.meta.url), "utf8"));
const project = await readFile(new URL("godot-cymonkey-fixture/project.godot", import.meta.url), "utf8");
const container = await readFile(new URL("../infra/deploy/godot-cymonkey-fixture/Containerfile", import.meta.url), "utf8");
const goProtocol = await readFile(new URL("../src/jangolova/contract/protocol.go", import.meta.url), "utf8");

assert.match(protocol, /cymonkey\/v1alpha1/);
assert.equal(protocol.match(/VERSION := "([^"]+)"/)?.[1], goProtocol.match(/ProtocolVersion\s+= "([^"]+)"/)?.[1]);
assert.doesNotMatch(registry, /compatibleProtocols/);
assert.match(registry, /"domains": \[CymonkeyProtocol\.DOMAIN_RENDER\]/);
assert.match(registry, /"runtimes": \[CymonkeyProtocol\.RUNTIME_GODOT\]/);
assert.match(registry, /"drivers": \[CymonkeyProtocol\.DRIVER_WEBSOCKET\]/);
assert.match(registry, /stale_revision/);
for (const method of ["hello", "capabilities", "describe", "act", "events", "health"]) assert.match(protocol, new RegExp(`METHOD_[A-Z]+ := "${method}"`));
for (const kind of ["scene", "object", "ui", "camera", "material", "animation", "timeline", "artifact", "event"]) assert.match(protocol, new RegExp(`"${kind}"`));
assert.match(registry, /registrations/);
assert.match(registry, /is_stable_id/);
assert.match(registry, /action_not_allowlisted/);
assert.match(registry, /event:resource-changed/);
assert.doesNotMatch(registry, /get_tree\(\)\.get_nodes_in_group|get_nodes_in_group|get_children\(\)/);
assert.match(host, /bearer_token/);
assert.match(host, /MAXIMUM_MESSAGE_BYTES/);
assert.match(host, /TCPServer/);
assert.match(host, /WebSocketPeer/);
assert.doesNotMatch(host, /get_tree\(\)\.quit|quit\(\)|OS\.kill/);
assert.match(fixture, /object:fixture/);
for (const resource of ["object:house", "object:door", "object:hero", "material:interior-light", "camera:main", "ui:status"]) assert.match(fixture, new RegExp(resource.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")));
for (const action of ["object.transform.set", "material.color.set", "camera.transform.set", "ui.text.set"]) assert.match(registry, new RegExp(action.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")));
for (const node of ["House", "Door", "WindowLeft", "WindowRight", "InteriorLight", "Hero", "Status", "CameraMain"]) assert.match(scene, new RegExp(`name=\\"${node}\\"`));
assert.match(fixture, /object\.visible\.set/);
assert.match(fixture, /JANGOLOVA_CAPTURE_PATH/);
assert.equal(scenePlan.apiVersion, "cymonkey.scene/v1alpha1");
assert.equal(scenePlan.name, "midnight-house");
assert.equal(scenePlan.actions.length, 5);
assert.ok(scenePlan.requires.some((resource) => resource.id === "material:interior-light"));
assert.match(project, /run\/main_scene/);
assert.match(container, /--headless/);
assert.match(container, /GODOT_IMAGE/);
assert.doesNotMatch(container, /JANGOLOVA_CYMONKEY_TOKEN=.*[A-Za-z0-9]{8}/);
console.log("Godot Cymonkey fixture environment contract is valid.");
