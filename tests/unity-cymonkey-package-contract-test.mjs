import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const root = new URL("../pkg/unity-cymonkey/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("package.json", root)));
const protocol = await readFile(new URL("Runtime/CymonkeyProtocol.cs", root), "utf8");
const bridge = await readFile(new URL("Runtime/CymonkeyBridge.cs", root), "utf8");
const server = await readFile(new URL("Runtime/CymonkeyWebSocketServer.cs", root), "utf8");
const host = await readFile(new URL("Runtime/CymonkeyWebSocketHost.cs", root), "utf8");
const transport = await readFile(new URL("Runtime/ICymonkeyTransportHost.cs", root), "utf8");
const goProtocol = await readFile(new URL("../src/jangolova/contract/protocol.go", import.meta.url), "utf8");

assert.equal(manifest.name, "com.cymonkey.jangolova");
assert.equal(manifest.unity, "2022.3");
const unityVersion = protocol.match(/Version = "([^"]+)"/)?.[1];
const goVersion = goProtocol.match(/ProtocolVersion\s+= "([^"]+)"/)?.[1];
assert.equal(unityVersion, "cymonkey/v1alpha1");
assert.equal(unityVersion, goVersion);
for (const method of ["hello", "capabilities", "describe", "act", "events", "health"]) assert.ok(bridge.includes(`"${method}"`));
for (const kind of ["scene", "object", "ui", "camera", "material", "animation", "timeline", "artifact", "event"]) assert.ok(protocol.includes(kind));
assert.match(bridge, /Explicit action allowlist|action_not_allowlisted/);
assert.match(bridge, /StableId/);
assert.doesNotMatch(bridge, /FindObjectsOfType|Resources\.FindObjects/);
assert.match(transport, /interface ICymonkeyTransportHost/);
assert.match(host, /ICymonkeyTransportHost/);
assert.match(bridge, /public JToken Dispatch/);
assert.doesNotMatch(bridge, /HttpListener|PacmanWebSocketServer/);
assert.match(server, /HttpListener/);
assert.match(server, /Authorization/);
assert.match(server, /ConstantTimeEquals/);
assert.doesNotMatch(server, /Application\.Quit|Process\.Kill/);
console.log("Unity Cymonkey package contract is valid.");
