package browserextension

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

// BuildResult identifies an artifact produced with the caller's browser,
// Mozilla account, or Apple signing identity. It never implies installation.
type BuildResult struct {
	Status           string `json:"status"`
	Browser          string `json:"browser"`
	Source           string `json:"source"`
	SourceRevision   string `json:"sourceRevision"`
	ArtifactRevision string `json:"artifactRevision"`
	KeyPath          string `json:"keyPath,omitempty"`
	NextAction       string `json:"nextAction,omitempty"`
}

func checkedSource(source, revision string) (Description, error) {
	if revision == "" {
		return Description{}, errors.New("a prepared source revision is required")
	}
	description, err := Inspect(source)
	if err != nil {
		return Description{}, err
	}
	if description.Revision != revision {
		return Description{}, errors.New("extension changed since inspection")
	}
	return description, nil
}

func unusedArtifact(path, extension string) error {
	if !filepath.IsAbs(path) || !strings.EqualFold(filepath.Ext(path), extension) {
		return fmt.Errorf("output must be an absolute %s path", extension)
	}
	if _, err := os.Lstat(path); err == nil {
		return fmt.Errorf("output already exists: %s", path)
	} else if !os.IsNotExist(err) {
		return err
	}
	return os.MkdirAll(filepath.Dir(path), 0755)
}

func outsideSource(source, output string) error {
	info, err := os.Stat(source)
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return nil
	}
	root, err := filepath.Abs(source)
	if err != nil {
		return err
	}
	target, err := filepath.Abs(output)
	if err != nil {
		return err
	}
	if target == root || strings.HasPrefix(target, root+string(filepath.Separator)) {
		return errors.New("artifact and private key paths must be outside the extension source")
	}
	return nil
}

func copyArtifactExclusive(source, destination string, mode os.FileMode) error {
	input, err := os.Open(source)
	if err != nil {
		return err
	}
	defer input.Close()
	output, err := os.OpenFile(destination, os.O_CREATE|os.O_EXCL|os.O_WRONLY, mode)
	if err != nil {
		return err
	}
	_, copyErr := io.Copy(output, input)
	closeErr := output.Close()
	if copyErr != nil || closeErr != nil {
		_ = os.Remove(destination)
		return errors.Join(copyErr, closeErr)
	}
	return nil
}

func fileSHA256(path string) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer file.Close()
	hash := sha256.New()
	if _, err := io.Copy(hash, file); err != nil {
		return "", err
	}
	return "sha256:" + hex.EncodeToString(hash.Sum(nil)), nil
}

// SignChromiumCRX asks the caller's Chrome-family executable to pack a CRX.
// A missing key is generated by the browser and saved next to the CRX; it must
// be kept by the caller for updates. This does not install the CRX.
func SignChromiumCRX(ctx context.Context, browser, executable, source, output, revision, keyPath string) (BuildResult, error) {
	if browser != "chrome" && browser != "chromium" && browser != "edge" {
		return BuildResult{}, errors.New("CRX signing requires chrome, chromium, or edge")
	}
	if !filepath.IsAbs(executable) {
		return BuildResult{}, errors.New("browser executable must be an absolute path")
	}
	if info, err := os.Stat(executable); err != nil || !info.Mode().IsRegular() {
		return BuildResult{}, fmt.Errorf("browser executable is unavailable: %s", executable)
	}
	description, err := checkedSource(source, revision)
	if err != nil {
		return BuildResult{}, err
	}
	if err := outsideSource(source, output); err != nil {
		return BuildResult{}, err
	}
	if err := unusedArtifact(output, ".crx"); err != nil {
		return BuildResult{}, err
	}
	generatedKey := keyPath == ""
	if generatedKey {
		keyPath = strings.TrimSuffix(output, filepath.Ext(output)) + ".pem"
		if err := outsideSource(source, keyPath); err != nil {
			return BuildResult{}, err
		}
		if err := unusedArtifact(keyPath, ".pem"); err != nil {
			return BuildResult{}, err
		}
	} else {
		if !filepath.IsAbs(keyPath) {
			return BuildResult{}, errors.New("existing key path must be absolute")
		}
		info, err := os.Lstat(keyPath)
		if err != nil || !info.Mode().IsRegular() {
			return BuildResult{}, errors.New("existing key must be a regular file, not a symlink")
		}
	}
	if err := outsideSource(source, keyPath); err != nil {
		return BuildResult{}, err
	}
	work, err := os.MkdirTemp("", "jangolova-crx-")
	if err != nil {
		return BuildResult{}, err
	}
	defer os.RemoveAll(work)
	staged := filepath.Join(work, "extension")
	if _, err := StageWithRevision(source, staged, revision); err != nil {
		return BuildResult{}, err
	}
	args := []string{"--no-first-run", "--no-default-browser-check", "--user-data-dir=" + filepath.Join(work, "browser-data"), "--pack-extension=" + staged}
	if !generatedKey {
		args = append(args, "--pack-extension-key="+keyPath)
	}
	if outputText, err := exec.CommandContext(ctx, executable, args...).CombinedOutput(); err != nil {
		return BuildResult{}, fmt.Errorf("browser CRX packaging failed: %w: %s", err, strings.TrimSpace(string(outputText)))
	}
	crx := staged + ".crx"
	file, err := os.Open(crx)
	if err != nil {
		return BuildResult{}, errors.New("browser did not produce a CRX")
	}
	var magic [4]byte
	_, readErr := io.ReadFull(file, magic[:])
	_ = file.Close()
	if readErr != nil || string(magic[:]) != "Cr24" {
		return BuildResult{}, errors.New("browser output is not a CRX")
	}
	if current, err := Inspect(source); err != nil || current.Revision != revision {
		return BuildResult{}, errors.New("extension changed during CRX packaging")
	}
	if generatedKey {
		if err := copyArtifactExclusive(staged+".pem", keyPath, 0600); err != nil {
			return BuildResult{}, fmt.Errorf("save generated private key: %w", err)
		}
	}
	if err := copyArtifactExclusive(crx, output, 0644); err != nil {
		if generatedKey {
			_ = os.Remove(keyPath)
		}
		return BuildResult{}, err
	}
	artifactRevision, err := fileSHA256(output)
	if err != nil {
		return BuildResult{}, err
	}
	return BuildResult{Status: "signed", Browser: browser, Source: output, SourceRevision: description.Revision,
		ArtifactRevision: artifactRevision, KeyPath: keyPath,
		NextAction: "Keep the private key for updates. Chrome installation rules still apply; use the original source with extension install or run for local loading."}, nil
}

// SignFirefoxXPI uses the caller's web-ext and AMO API credentials. Mozilla
// signs the XPI; the credentials are read from web-ext's environment variables
// and are never passed in process arguments or returned to Cymonkey callers.
func SignFirefoxXPI(ctx context.Context, source, output, revision string) (BuildResult, error) {
	description, err := checkedSource(source, revision)
	if err != nil {
		return BuildResult{}, err
	}
	if err := outsideSource(source, output); err != nil {
		return BuildResult{}, err
	}
	if err := unusedArtifact(output, ".xpi"); err != nil {
		return BuildResult{}, err
	}
	if os.Getenv("WEB_EXT_API_KEY") == "" || os.Getenv("WEB_EXT_API_SECRET") == "" {
		return BuildResult{}, errors.New("Firefox signing requires WEB_EXT_API_KEY and WEB_EXT_API_SECRET for the caller's Mozilla account")
	}
	tool, err := exec.LookPath("web-ext")
	if err != nil {
		return BuildResult{}, errors.New("Firefox signing requires web-ext on PATH")
	}
	work, err := os.MkdirTemp("", "jangolova-firefox-sign-")
	if err != nil {
		return BuildResult{}, err
	}
	defer os.RemoveAll(work)
	staged := filepath.Join(work, "extension")
	if _, err := StageWithRevision(source, staged, revision); err != nil {
		return BuildResult{}, err
	}
	artifacts := filepath.Join(work, "artifacts")
	if err := os.Mkdir(artifacts, 0700); err != nil {
		return BuildResult{}, err
	}
	command := exec.CommandContext(ctx, tool, "sign", "--no-input", "--no-config-discovery", "--channel=unlisted", "--source-dir="+staged, "--artifacts-dir="+artifacts)
	command.Dir = work
	if _, err := command.CombinedOutput(); err != nil {
		return BuildResult{}, fmt.Errorf("Mozilla signing failed: %w; check the extension ID, account permissions, and AMO submission status", err)
	}
	entries, err := os.ReadDir(artifacts)
	if err != nil {
		return BuildResult{}, err
	}
	var signed string
	for _, entry := range entries {
		if strings.EqualFold(filepath.Ext(entry.Name()), ".xpi") && entry.Type().IsRegular() {
			if signed != "" {
				return BuildResult{}, errors.New("web-ext produced multiple XPIs")
			}
			signed = filepath.Join(artifacts, entry.Name())
		}
	}
	if signed == "" {
		return BuildResult{}, errors.New("web-ext did not produce a signed XPI")
	}
	if current, err := Inspect(source); err != nil || current.Revision != revision {
		return BuildResult{}, errors.New("extension changed during Mozilla signing")
	}
	if err := copyArtifactExclusive(signed, output, 0644); err != nil {
		return BuildResult{}, err
	}
	signedDescription, err := Inspect(output)
	if err != nil {
		_ = os.Remove(output)
		return BuildResult{}, fmt.Errorf("signed XPI inspection failed: %w", err)
	}
	return BuildResult{Status: "signed", Browser: "firefox", Source: output, SourceRevision: description.Revision,
		ArtifactRevision: signedDescription.Revision,
		NextAction:       "Use the signed XPI and artifactRevision with extension install for the selected Firefox profile."}, nil
}

// BuildSafariApp builds and signs a caller-owned Xcode project for local
// Safari use. App Store distribution and Developer ID notarization are separate.
func BuildSafariApp(ctx context.Context, project, scheme, output, teamID string) (BuildResult, error) {
	if runtime.GOOS != "darwin" {
		return BuildResult{}, errors.New("Safari app building requires macOS and Xcode")
	}
	if !filepath.IsAbs(project) || !strings.EqualFold(filepath.Ext(project), ".xcodeproj") ||
		strings.TrimSpace(scheme) == "" || teamID == "" || strings.ContainsAny(teamID, " \t\n=") {
		return BuildResult{}, errors.New("Safari building requires an absolute .xcodeproj path, scheme, and developer team ID")
	}
	if info, err := os.Stat(project); err != nil || !info.IsDir() {
		return BuildResult{}, errors.New("Safari Xcode project is unavailable")
	}
	if path := filepath.Clean(output); path == filepath.Clean(project) || strings.HasPrefix(path, filepath.Clean(project)+string(filepath.Separator)) {
		return BuildResult{}, errors.New("signed app output must be outside the Xcode project")
	}
	if err := unusedArtifact(output, ".app"); err != nil {
		return BuildResult{}, err
	}
	work, err := os.MkdirTemp("", "jangolova-safari-build-")
	if err != nil {
		return BuildResult{}, err
	}
	defer os.RemoveAll(work)
	derived := filepath.Join(work, "derived")
	command := exec.CommandContext(ctx, "xcodebuild", "-project", project, "-scheme", scheme,
		"-configuration", "Release", "-destination", "generic/platform=macOS", "-derivedDataPath", derived,
		"DEVELOPMENT_TEAM="+teamID, "CODE_SIGN_STYLE=Automatic", "CODE_SIGNING_ALLOWED=YES", "build")
	if outputText, err := command.CombinedOutput(); err != nil {
		return BuildResult{}, fmt.Errorf("Safari Xcode build failed: %w: %s", err, strings.TrimSpace(string(outputText)))
	}
	products := filepath.Join(derived, "Build", "Products", "Release")
	entries, err := os.ReadDir(products)
	if err != nil {
		return BuildResult{}, err
	}
	var app string
	for _, entry := range entries {
		if entry.IsDir() && strings.EqualFold(filepath.Ext(entry.Name()), ".app") {
			if app != "" {
				return BuildResult{}, errors.New("Xcode produced multiple apps; select a single-app scheme")
			}
			app = filepath.Join(products, entry.Name())
		}
	}
	if app == "" {
		return BuildResult{}, errors.New("Xcode did not produce a macOS app")
	}
	if description, err := InspectSafariApp(ctx, app); err != nil || description.Revision == "" {
		return BuildResult{}, fmt.Errorf("built Safari app is not signed with a Safari WebExtension: %w", err)
	}
	if err := os.Mkdir(output, 0700); err != nil {
		return BuildResult{}, fmt.Errorf("reserve signed Safari app output: %w", err)
	}
	if outputText, err := exec.CommandContext(ctx, "ditto", app, output).CombinedOutput(); err != nil {
		_ = os.RemoveAll(output)
		return BuildResult{}, fmt.Errorf("copy signed Safari app: %w: %s", err, strings.TrimSpace(string(outputText)))
	}
	if info, err := os.Stat(app); err == nil {
		if err := os.Chmod(output, info.Mode().Perm()); err != nil {
			_ = os.RemoveAll(output)
			return BuildResult{}, err
		}
	}
	description, err := InspectSafariApp(ctx, output)
	if err != nil {
		_ = os.RemoveAll(output)
		return BuildResult{}, err
	}
	return BuildResult{Status: "signed", Browser: "safari", Source: output, ArtifactRevision: description.Revision,
		NextAction: "Use the signed app and artifactRevision with extension install, then enable it in Safari Settings. Distribution may require Developer ID signing and notarization."}, nil
}
